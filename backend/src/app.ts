import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import { rateLimit } from 'express-rate-limit';
import { PrismaClient } from '@prisma/client';
import { ZodError } from 'zod';
import { router } from './routes';
import { registerEvents } from './events';
export const prisma = new PrismaClient();
registerEvents(prisma);
const app = express();
app.set('trust proxy', 1);
app.use(helmet());
app.use(cors({ origin: process.env.FRONTEND_URL || 'http://localhost:3000', credentials: true }));
app.use(express.json({ limit: '1mb' }));
app.use('/api/auth/login', rateLimit({ windowMs: 900000, limit: 20 }));
app.get('/health', (_req, res) => res.json({ status: 'ok' }));
app.use('/api', router);
app.use((err: any, _req: express.Request, res: express.Response, _next: express.NextFunction) => { if(err instanceof ZodError)return res.status(400).json({error:'Invalid request',details:err.issues.map(issue=>({path:issue.path.join('.'),message:issue.message}))});console.error(err); const status=Number(err.status)||500; res.status(status).json({error:status===500?'Internal server error':err.message}); });
export default app;
